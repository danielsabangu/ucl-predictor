"""UCL Predictor V2 matchday presentation (no network or model calls).

Stage 1 shows the *published fixture and pre-match forecast snapshot*, never
synthetic scores or invented live event data. Real score data must be supplied
later by a separately licensed provider adapter.
"""
from __future__ import annotations

from dataclasses import dataclass
from datetime import datetime, timezone
from html import escape as html_escape
from typing import Mapping

import pandas as pd

from src.production.club_crests import crest_html


@dataclass(frozen=True)
class MatchScore:
    """Future provider-owned match state, not generated by the predictor."""

    home_goals: int | None = None
    away_goals: int | None = None
    status: str = "UNAVAILABLE"
    minute: int | None = None
    updated_at: datetime | None = None

    def __post_init__(self) -> None:
        if self.home_goals is not None and self.home_goals < 0:
            raise ValueError("Negative home goals")
        if self.away_goals is not None and self.away_goals < 0:
            raise ValueError("Negative away goals")
        if (self.home_goals is None) != (self.away_goals is None):
            raise ValueError("Both teams' scores must be present together")


def _safe(value: object) -> str:
    return html_escape(str(value), quote=True)


def _kickoff(row: Mapping[str, object]) -> pd.Timestamp:
    return pd.Timestamp(row["kickoff_utc"]).tz_convert("Africa/Johannesburg")


def _time(row: Mapping[str, object]) -> str:
    return _kickoff(row).strftime("%H:%M SAST")


def _is_started(row: Mapping[str, object], now: datetime | None) -> bool:
    now_utc = now or datetime.now(timezone.utc)
    if now_utc.tzinfo is None:
        raise ValueError("now must have timezone information")
    return pd.Timestamp(row["kickoff_utc"]) <= pd.Timestamp(now_utc)


def _fixture_status(row: Mapping[str, object], now: datetime | None) -> str:
    return "KICKOFF PASSED" if _is_started(row, now) else "UPCOMING"


def _one_crest(team: object, side: str) -> str:
    # Central crest mapping already owned by the app; never hotlink guesses.
    return crest_html(str(team), side=side)


def _score_view(score: MatchScore | None) -> tuple[str, str, str]:
    """Text, badge label and CSS class; never call unavailable scores live."""
    if score is None or score.home_goals is None:
        return "– : –", "SCORE FEED NOT CONNECTED", "unavailable"
    label = str(score.status).upper().strip()
    if label not in {"LIVE", "HALF_TIME", "FULL_TIME", "SCHEDULED"}:
        label = "SCORE STATUS UNKNOWN"
    if label == "LIVE" and score.minute is not None:
        label = f"LIVE · {int(score.minute)}′"
    return f"{score.home_goals} : {score.away_goals}", label, "connected"


def matchday_hero_html(data: pd.DataFrame, *, now: datetime | None = None) -> str:
    if data.empty:
        return '''<section class="md-hero"><div class="md-eyebrow">MATCHDAY HUB</div>
        <h1>THE NEXT FOOTBALL NIGHT STARTS HERE.</h1>
        <p>No matchday snapshot is available yet.</p></section>'''

    ordered = data.sort_values("kickoff_utc")
    # Feature the next printable fixture before kickoff; after the final kickoff,
    # retain the first snapshot match as a stable point of reference.
    next_rows = [row for _, row in ordered.iterrows() if not _is_started(row, now)]
    first = next_rows[0] if next_rows else ordered.iloc[0]
    date_label = _kickoff(ordered.iloc[0]).strftime("%A, %d %B %Y").upper()
    remaining = len(next_rows)
    return f'''
    <section class="md-hero">
      <div class="md-hero-glow"></div>
      <div class="md-eyebrow"><span class="md-star"></span> UCL PREDICTOR · MATCHDAY NIGHTS</div>
      <div class="md-hero-main">
        <div>
          <div class="md-date">{_safe(date_label)} · SAST</div>
          <h1>THE NIGHT<br><em>IS OURS.</em></h1>
          <p>Every match has a story. Every forecast has a receipt.<br>
          Make your call before kickoff, then follow the night.</p>
          <div class="md-hero-tags">
            <span>{len(ordered):02d} MATCHES ON THE BOARD</span>
            <span>{remaining:02d} AWAITING KICKOFF</span>
          </div>
        </div>
        <div class="md-hero-display" aria-label="Featured match">
          <div class="md-display-title">FEATURED FIXTURE · {_safe(_time(first))}</div>
          <div class="md-display-crests">
            {_one_crest(first['home_team'], 'home')}
            <b>VS</b>
            {_one_crest(first['away_team'], 'away')}
          </div>
          <div class="md-display-teams">
            {_safe(first['home_team'])} <span>×</span> {_safe(first['away_team'])}
          </div>
          <div class="md-display-caption">SCORES APPEAR ONLY WHEN A VERIFIED LIVE FEED IS CONNECTED</div>
        </div>
      </div>
    </section>'''


def matchday_section_heading(title: str, subtitle: str) -> str:
    return (f'<div class="md-section-heading"><div><div class="md-eyebrow">'
            f'MATCHDAY // UCL PREDICTOR V2</div><h2>{_safe(title)}</h2>'
            f'<p>{_safe(subtitle)}</p></div></div>')


def fixture_card_html(row: Mapping[str, object], *, now: datetime | None = None) -> str:
    home = _safe(row["home_team"])
    away = _safe(row["away_team"])
    status = _fixture_status(row, now)
    return f'''
    <div class="md-fixture-card">
      <div class="md-fixture-top"><span>{_safe(_time(row))}</span><span class="md-fixture-state">{status}</span></div>
      <div class="md-fixture-identity">
        <div class="md-fixture-club">{_one_crest(row['home_team'], 'home')}<span>{home}</span></div>
        <div class="md-versus">VS</div>
        <div class="md-fixture-club">{_one_crest(row['away_team'], 'away')}<span>{away}</span></div>
      </div>
      <div class="md-fixture-foot"><span>NO LIVE SCORE CONNECTED</span><span>VIEW</span></div>
    </div>'''


def scoreboard_html(
    row: Mapping[str, object],
    *,
    score: MatchScore | None = None,
    now: datetime | None = None,
) -> str:
    shown_score, score_status, score_class = _score_view(score)
    phase = _fixture_status(row, now)
    time_label = _time(row)
    actual_status = score_status if score_class == "connected" else phase
    return f'''
    <div class="md-scoreboard">
      <div class="md-scoreboard-top"><span>UCL PREDICTOR // MATCH CENTRE</span>
      <span class="md-score-feed {score_class}">{_safe(actual_status)}</span>
      <!-- {"SCORE FEED NOT CONNECTED" if score_class == "unavailable" else ""} --></div>
      <div class="md-scoreboard-core">
        <div class="md-score-team">{_one_crest(row['home_team'], 'home')}
          <strong>{_safe(row['home_team'])}</strong><span>HOME</span></div>
        <div class="md-score-centre"><div class="md-score-value">{_safe(shown_score)}</div>
          <div class="md-score-caption">{_safe(time_label)}</div></div>
        <div class="md-score-team">{_one_crest(row['away_team'], 'away')}
          <strong>{_safe(row['away_team'])}</strong><span>AWAY</span></div>
      </div>
      <div class="md-scoreboard-bottom">Pre-match forecasts are recorded before kickoff.
      Live score data is currently unavailable.</div>
    </div>'''


def forecast_vs_reality_html(
    row: Mapping[str, object],
    *,
    forecasts_available: bool = True,
    score: MatchScore | None = None,
) -> str:
    if not forecasts_available:
        return '''<section class="md-panel"><div class="md-panel-overline">FORECAST VS REALITY</div>
        <h3>Forecast temporarily unavailable</h3>
        <p>The production health checks have blocked this forecast. Matchday coverage stays separate.</p></section>'''
    pick = _safe(row["predicted_selection"])
    h = float(row["home_probability"]) * 100
    d = float(row["draw_probability"]) * 100
    a = float(row["away_probability"]) * 100
    current, _, score_class = _score_view(score)
    actual = current if score_class == "connected" else "NOT AVAILABLE"
    return f'''
    <section class="md-panel md-forecast-panel">
      <div class="md-panel-overline">THE PRE-MATCH RECEIPT</div>
      <h3>FORECAST <span>VS</span> REALITY</h3>
      <div class="md-forecast-row"><span>PRE-MATCH PICK</span><strong>{pick}</strong></div>
      <div class="md-forecast-row"><span>PROJECTED SCORE</span><strong>{_safe(row['predicted_scoreline'])}</strong></div>
      <div class="md-forecast-row"><span>ACTUAL SCORE</span><strong>{_safe(actual)}</strong></div>
      <div class="md-chance-title">ORIGINAL 1X2 PROBABILITIES</div>
      <div class="md-prob-track" role="img" aria-label="Home {h:.1f} percent, Draw {d:.1f} percent, Away {a:.1f} percent">
        <span style="width:{h:.3f}%"></span><span style="width:{d:.3f}%"></span><span style="width:{a:.3f}%"></span>
      </div>
      <div class="md-prob-legend"><span>HOME {h:.1f}%</span><span>DRAW {d:.1f}%</span><span>AWAY {a:.1f}%</span></div>
      <p class="md-panel-disclaimer">These are frozen pre-match probabilities, not live win probabilities.
      The forecast will never be changed to match the result.</p>
    </section>'''


